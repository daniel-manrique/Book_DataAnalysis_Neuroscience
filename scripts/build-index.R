# Builds index-of-terms.qmd and glossary.qmd from the book sources.
# Run automatically before every project render (see _quarto.yml), or by hand:
#   Rscript scripts/build-index.R
# Method: planning/glossary-index-method.md

root <- if (file.exists("_quarto.yml")) "." else stop("Run from the project root")
rd <- function(f) readLines(f, warn = FALSE, encoding = "UTF-8")

# Files in book order, taken from _quarto.yml
cfg <- rd(file.path(root, "_quarto.yml"))
chapter_lines <- grep("^\\s*-\\s+(part:\\s+)?[A-Za-z0-9_-]+\\.qmd", cfg, value = TRUE)
files <- unique(sub("^.*?([A-Za-z0-9_-]+\\.qmd).*$", "\\1", chapter_lines, perl = TRUE))
files <- setdiff(files, c("glossary.qmd", "index-of-terms.qmd", "references.qmd", "index.qmd"))
files <- c("index.qmd", files)

slugify <- function(s) {
  s <- tolower(s)
  s <- gsub("[^a-z0-9]+", "-", s)
  gsub("^-+|-+$", "", s)
}

# Same cleaning rule as filters/ix.lua: lower case, no quotes or markdown
# marks, no leading article
clean_term <- function(x) {
  x <- tolower(gsub("[`*_]", "", x))
  x <- gsub("[\"“”‘’]", "", x)
  x <- trimws(x)
  sub("^(a|an|the)\\s+", "", x)
}

excl_file <- file.path(root, "scripts", "index-exclude.txt")
excluded <- if (file.exists(excl_file)) {
  e <- trimws(rd(excl_file))
  e[nzchar(e) & !grepl("^#", e)]
} else character()

chapter_title <- function(L) {
  h1 <- grep("^# ", L, value = TRUE)
  if (length(h1)) return(trimws(sub("\\s*\\{[^}]*\\}\\s*$", "", sub("^# ", "", h1[1]))))
  t <- grep("^title:", L, value = TRUE)
  if (length(t)) return(trimws(sub("^title:\\s*", "", t[1])))
  NA_character_
}

in_chunk <- function(L) {
  st <- FALSE
  v <- logical(length(L))
  for (i in seq_along(L)) {
    if (!st && grepl("^\\s*```\\{", L[i])) { st <- TRUE; v[i] <- TRUE; next }
    if (st && grepl("^\\s*```\\s*$", L[i])) { st <- FALSE; v[i] <- TRUE; next }
    v[i] <- st
  }
  v
}

marks <- list()
for (f in files) {
  p <- file.path(root, f)
  if (!file.exists(p)) next
  L <- rd(p)
  title <- chapter_title(L)
  L[in_chunk(L)] <- ""
  txt <- paste(L, collapse = "\n")
  m <- gregexpr("\\[[^]\n]+\\]\\{[^}\n]*\\}", txt)[[1]]
  if (m[1] == -1) next
  spans <- regmatches(txt, list(m))[[1]]
  counts <- list()
  for (s in spans) {
    body <- sub("^\\[(.*)\\]\\{.*\\}$", "\\1", s)
    attrs <- sub("^\\[.*\\]\\{(.*)\\}$", "\\1", s)
    is_ix <- grepl("(^|\\s)\\.ix(\\s|$)", attrs)
    is_def <- grepl("color:\\s*green", attrs)
    if (!is_ix && !is_def) next
    canon <- if (grepl("ix=\"", attrs)) sub("^.*ix=\"([^\"]*)\".*$", "\\1", attrs) else body
    canon <- clean_term(canon)
    slug <- slugify(canon)
    if (slug == "") next
    # Long green-only phrases are emphasis, not terms; so are excluded terms
    n_words <- lengths(strsplit(canon, "\\s+"))
    if (!is_ix && n_words > 4) next
    if (canon %in% excluded) next
    counts[[slug]] <- (if (is.null(counts[[slug]])) 0 else counts[[slug]]) + 1
    marks[[length(marks) + 1]] <- data.frame(
      term = tolower(canon), slug = slug, file = f, title = title,
      id = paste0("ix-", slug, "-", counts[[slug]]), def = is_def,
      stringsAsFactors = FALSE)
  }
}
M <- if (length(marks)) do.call(rbind, marks) else data.frame()

# Glossary entries (hand-written, see glossary-terms.yml)
gl <- list()
if (file.exists(file.path(root, "glossary-terms.yml"))) {
  gl <- yaml::read_yaml(file.path(root, "glossary-terms.yml"))
}

write_if_changed <- function(path, lines) {
  new <- paste(lines, collapse = "\n")
  old <- if (file.exists(path)) paste(rd(path), collapse = "\n") else ""
  if (!identical(trimws(new), trimws(old))) writeLines(lines, path, useBytes = TRUE)
}

# One link per chapter; extra marks in the same chapter appear as (2), (3), ...
links_for <- function(sub) {
  out <- character()
  for (f in unique(sub$file)) {
    s <- sub[sub$file == f, ]
    first <- sprintf("[%s](%s#%s)", s$title[1], f, s$id[1])
    rest <- ""
    if (nrow(s) > 1) {
      more <- sprintf("[%d](%s#%s)", 2:nrow(s), f, s$id[-1])
      rest <- paste0(" (", paste(more, collapse = ", "), ")")
    }
    out <- c(out, paste0(first, rest))
  }
  out
}

# ---- Index of key terms ----
idx <- c("# Index of key terms {.unnumbered #sec-index-of-terms}", "",
         "<!-- GENERATED by scripts/build-index.R. Do not edit by hand; mark terms in the chapters instead. Method: planning/glossary-index-method.md -->", "",
         "::: {.content-visible when-format=\"html\"}", "")
gl_keys <- vapply(gl, function(e) slugify(e$term), character(1))
if (nrow(M)) {
  terms <- sort(unique(M$term))
  letter <- toupper(substr(terms, 1, 1))
  for (L1 in sort(unique(letter))) {
    idx <- c(idx, paste0("## ", L1, " {.unnumbered .unlisted}"), "")
    for (t in terms[letter == L1]) {
      sub <- M[M$term == t, ]
      gtag <- if (slugify(t) %in% gl_keys) sprintf(" ([glossary](glossary.qmd#gl-%s))", slugify(t)) else ""
      idx <- c(idx, paste0("- **", t, "**", gtag, ": ", paste(links_for(sub), collapse = "; ")))
    }
    idx <- c(idx, "")
  }
} else {
  idx <- c(idx, "No terms are marked yet.", "")
}
idx <- c(idx, ":::", "", "::: {.content-visible when-format=\"pdf\"}", "", "```{=latex}", "\\printindex", "```", "", ":::")
write_if_changed(file.path(root, "index-of-terms.qmd"), idx)

# ---- Glossary ----
g <- c("# Glossary {.unnumbered #sec-glossary}", "",
       "<!-- GENERATED by scripts/build-index.R from glossary-terms.yml. Do not edit by hand. Method: planning/glossary-index-method.md -->", "")
if (length(gl)) {
  ord <- order(tolower(vapply(gl, function(e) e$term, character(1))))
  for (e in gl[ord]) {
    slug <- slugify(e$term)
    g <- c(g, sprintf("## %s {#gl-%s .unnumbered .unlisted}", tools::toTitleCase(e$term), slug), "",
           trimws(e$definition), "")
    if (!is.null(e$analogy)) g <- c(g, paste0("*Think of it as:* ", trimws(e$analogy)), "")
    if (!is.null(e$see_also)) {
      sa <- sprintf("[%s](#gl-%s)", e$see_also, vapply(e$see_also, slugify, character(1)))
      g <- c(g, paste0("*See also:* ", paste(sa, collapse = ", ")), "")
    }
    sub <- if (nrow(M)) M[M$slug == slug, ] else M
    if (nrow(sub)) {
      g <- c(g, "::: {.content-visible when-format=\"html\"}", "",
             paste0("*Where it appears:* ", paste(links_for(sub), collapse = "; ")), "", ":::", "")
    }
  }
} else {
  g <- c(g, "No entries yet.", "")
}
write_if_changed(file.path(root, "glossary.qmd"), g)

cat(sprintf("build-index: %d marks, %d distinct terms, %d glossary entries\n",
            nrow(M), length(unique(M$slug)), length(gl)))
